/**
 * Returns filtered list of universities for a typed location query or selected city/town
 */
export function getUniversitiesForLocation(locationQuery?: string): string[] {
  if (!locationQuery || !locationQuery.trim()) {
    return UNIVERSITIES_LIST;
  }

  const query = locationQuery.toLowerCase().trim();

  // Check if query directly or partially matches any suburb lookup
  for (const [suburbKey, cityName] of Object.entries(SUBURB_CITY_LOOKUP)) {
    if (query.includes(suburbKey) || suburbKey.includes(query)) {
      if (CITY_UNIVERSITIES_MAP[cityName]) {
        return CITY_UNIVERSITIES_MAP[cityName];
      }
    }
  }

  // Check if query matches a city name in the map
  for (const [cityName, unis] of Object.entries(CITY_UNIVERSITIES_MAP)) {
    if (cityName.toLowerCase().includes(query) || query.includes(cityName.toLowerCase())) {
      return unis;
    }
  }

  // If no specific city matched, return all universities
  return UNIVERSITIES_LIST;
}

